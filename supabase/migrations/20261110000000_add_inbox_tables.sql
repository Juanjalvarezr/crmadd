CREATE POLICY "anon_all_conversations" ON public.conversations FOR ALL TO anon USING (true) WITH CHECK (true);
CREATE POLICY "anon_all_conversation_messages" ON public.conversation_messages FOR ALL TO anon USING (true) WITH CHECK (true);
CREATE POLICY "anon_all_webhook_events_log" ON public.webhook_events_log FOR ALL TO anon USING (true) WITH CHECK (true);

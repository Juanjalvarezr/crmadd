-- ============================================================
-- CRM DESEO DIGITAL - Inbox unificado multi-canal (Fase 1)
-- Tablas aditivas para chats de WhatsApp (OpenWA) y Meta Cloud API.
-- No toca tablas existentes. Ejecutar en Supabase SQL Editor.
-- ============================================================

-- 1. Canales conectados
CREATE TABLE IF NOT EXISTS public.channels (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nombre text not null,
  activo boolean default true,
  config jsonb default '{}'::jsonb,
  creado_en timestamptz default now()
);

-- 2. Contactos por canal
CREATE TABLE IF NOT EXISTS public.channel_contacts (
  id bigint generated by default as identity primary key,
  channel_id bigint not null references public.channels(id),
  external_id text not null,
  nombre text,
  telefono text,
  email text,
  metadata jsonb default '{}'::jsonb,
  creado_en timestamptz default now(),
  actualizado_en timestamptz default now(),
  unique(channel_id, external_id)
);

-- 3. Conversaciones
CREATE TABLE IF NOT EXISTS public.conversations (
  id bigint generated by default as identity primary key,
  channel_id bigint not null references public.channels(id),
  contact_id bigint not null references public.channel_contacts(id),
  estado text default 'abierta',
  asignado_a text,
  ultimo_mensaje text,
  ultimo_mensaje_en timestamptz,
  creado_en timestamptz default now(),
  actualizado_en timestamptz default now()
);

-- 4. Mensajes
CREATE TABLE IF NOT EXISTS public.conversation_messages (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null references public.conversations(id),
  external_id text,
  direccion text default 'inbound',
  tipo text default 'texto',
  cuerpo text,
  media_url text,
  estado text default 'recibido',
  enviado_por text,
  creado_en timestamptz default now()
);

-- 5. Raw log de webhooks (auditoria + replay)
CREATE TABLE IF NOT EXISTS public.webhook_events_log (
  id bigint generated by default as identity primary key,
  canal text,
  external_id text,
  raw jsonb,
  status text default 'received',
  error text,
  procesado_en timestamptz,
  creado_en timestamptz default now()
);

-- 6. Plantillas de mensaje
CREATE TABLE IF NOT EXISTS public.message_templates (
  id bigint generated by default as identity primary key,
  tipo text default 'quick_reply',
  nombre text not null,
  categoria text,
  cuerpo text,
  variables jsonb default '[]'::jsonb,
  meta_template_id text,
  estado text default 'activa',
  creado_en timestamptz default now()
);

-- 7. Opt-out
CREATE TABLE IF NOT EXISTS public.opt_out (
  id bigint generated by default as identity primary key,
  channel_id bigint not null references public.channels(id),
  contacto text not null,
  motivo text,
  creado_en timestamptz default now(),
  unique(channel_id, contacto)
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_conv_channel ON public.conversations(channel_id);
CREATE INDEX IF NOT EXISTS idx_conv_contact ON public.conversations(contact_id);
CREATE INDEX IF NOT EXISTS idx_msg_conversation ON public.conversation_messages(conversation_id);
CREATE INDEX IF NOT EXISTS idx_webhook_external ON public.webhook_events_log(external_id);


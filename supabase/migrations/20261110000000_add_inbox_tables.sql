ALTER TABLE public.webhook_events_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.message_templates ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.opt_out ENABLE ROW LEVEL SECURITY;


-- ============================================================
-- CRM DESEO DIGITAL — Estado de sincronización n8n <-> OpenWA
-- ============================================================
CREATE TABLE IF NOT EXISTS public.crm_sync_state (
  id integer generated by default as identity primary key,
  nombre text not null unique,
  ultimo_sync timestamptz,
  registros_procesados integer default 0,
  ultimo_error text,
  activo boolean default true,
  creado_en timestamptz default now()
);

INSERT INTO public.crm_sync_state (nombre, activo)
VALUES ('openwa_outbound', true), ('planificador_seguimientos', true)
ON CONFLICT (nombre) DO NOTHING;

ALTER TABLE public.crm_sync_state ENABLE ROW LEVEL SECURITY;
CREATE POLICY "anon_all_crm_sync_state" ON public.crm_sync_state
  FOR ALL TO anon USING (true) WITH CHECK (true);

-- Índice para la cola de salida que n8n consume
CREATE INDEX IF NOT EXISTS idx_conv_msgs_pending
  ON public.conversation_messages (estado, creado_en)
  WHERE estado = 'pending';
